export function maskPhoneNumber(phone?: string | null): string {
  if (!phone) return '******0000'
  const cleaned = phone.replace(/\D/g, '')
  if (cleaned.length >= 4) {
    const last4 = cleaned.slice(-4)
    return `******${last4}`
  }
  return '******'
}
